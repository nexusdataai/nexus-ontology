"""
License Key Generator

Generates valid license keys with proper ECDSA signatures for testing purposes.
This module should only be used in development/testing environments.
"""

import base64
from datetime import datetime, timezone, timedelta
from typing import Optional, List
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.backends import default_backend

from ..models.enums import LicenseTier, TIER_TO_ABBREVIATION
from ..models.license_model import ParsedLicenseKey
from ..consts import TIER_FEATURES


class LicenseKeyGenerator:
    """
    Generator for creating valid license keys with proper signatures.
    
    WARNING: This is for testing purposes only. In production, license keys
    should be generated by a secure license server with proper key management.
    """
    
    def __init__(self, private_key_pem: Optional[str] = None):
        """
        Initialize with private key for signing.
        
        Args:
            private_key_pem: PEM-encoded private key. If None, uses default development key.
        """
        if private_key_pem:
            self._private_key = self._load_private_key(private_key_pem)
        else:
            # Use default development key for testing
            from .keys import get_private_key_pem
            self._private_key = self._load_private_key(get_private_key_pem())
        self._public_key = self._private_key.public_key()
    
    def _load_private_key(self, pem: str) -> ec.EllipticCurvePrivateKey:
        """Load private key from PEM string."""
        return serialization.load_pem_private_key(
            pem.encode('utf-8'),
            password=None,
            backend=default_backend()
        )
    
    def get_public_key_pem(self) -> str:
        """Get the public key PEM for verification."""
        return self._public_key.public_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PublicFormat.SubjectPublicKeyInfo
        ).decode('utf-8')
    
    def get_private_key_pem(self) -> str:
        """Get the private key PEM (for testing only)."""
        return self._private_key.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption()
        ).decode('utf-8')
    
    def generate_key(
        self,
        tier: LicenseTier,
        holder_id: str,
        expiration: Optional[datetime] = None,
        features: Optional[str] = None,
        version: str = "v1",
    ) -> str:
        """
        Generate a signed license key.
        
        Args:
            tier: License tier level
            holder_id: Customer/holder identifier
            expiration: Expiration date (defaults to 1 year from now)
            features: Feature string (defaults based on tier)
            version: License format version
            
        Returns:
            Complete signed license key string
        """
        # Default expiration to 1 year from now
        if expiration is None:
            expiration = datetime.now(timezone.utc) + timedelta(days=365)
        
        # Default features based on tier
        if features is None:
            if tier == LicenseTier.ENTERPRISE:
                features = "ALL"
            else:
                tier_features = TIER_FEATURES.get(tier, [])
                features = ",".join(tier_features).upper() if tier_features else "BASIC"
        
        # Build the data to sign
        tier_abbrev = TIER_TO_ABBREVIATION[tier]
        expiration_str = expiration.strftime("%Y%m%d")
        data_to_sign = f"{version}.{tier_abbrev}.{expiration_str}.{holder_id}.{features}"
        
        # Sign the data
        signature = self._sign(data_to_sign)
        
        # Build complete key
        return f"{data_to_sign}.{signature}"
    
    def _sign(self, data: str) -> str:
        """Sign data and return base64-encoded signature."""
        signature_bytes = self._private_key.sign(
            data.encode('utf-8'),
            ec.ECDSA(hashes.SHA256())
        )
        return base64.urlsafe_b64encode(signature_bytes).decode('utf-8').rstrip('=')
    
    def generate_expired_key(
        self,
        tier: LicenseTier,
        holder_id: str,
        days_expired: int = 30,
    ) -> str:
        """Generate a key that is already expired."""
        expiration = datetime.now(timezone.utc) - timedelta(days=days_expired)
        return self.generate_key(tier, holder_id, expiration)
    
    def generate_expiring_soon_key(
        self,
        tier: LicenseTier,
        holder_id: str,
        days_until_expiration: int = 7,
    ) -> str:
        """Generate a key that expires soon."""
        expiration = datetime.now(timezone.utc) + timedelta(days=days_until_expiration)
        return self.generate_key(tier, holder_id, expiration)
    
    def generate_test_keys(self, holder_id: str = "TEST-001") -> dict:
        """
        Generate a set of test keys for all tiers.
        
        Returns:
            Dict with tier names as keys and license keys as values
        """
        return {
            "basic": self.generate_key(LicenseTier.BASIC, holder_id),
            "professional": self.generate_key(LicenseTier.PROFESSIONAL, holder_id),
            "enterprise": self.generate_key(LicenseTier.ENTERPRISE, holder_id),
            "expired": self.generate_expired_key(LicenseTier.BASIC, holder_id),
            "expiring_soon": self.generate_expiring_soon_key(LicenseTier.BASIC, holder_id),
        }


# Singleton generator for testing convenience
_test_generator: Optional[LicenseKeyGenerator] = None


def get_test_generator() -> LicenseKeyGenerator:
    """Get or create a test key generator singleton."""
    global _test_generator
    if _test_generator is None:
        _test_generator = LicenseKeyGenerator()
    return _test_generator


def generate_test_key(
    tier: LicenseTier = LicenseTier.ENTERPRISE,
    holder_id: str = "TEST-001",
    days_valid: int = 365,
) -> str:
    """
    Convenience function to generate a test license key.
    
    Returns both the key and sets up the public key for verification.
    """
    from .keys import set_public_key
    
    generator = get_test_generator()
    set_public_key(generator.get_public_key_pem())
    
    expiration = datetime.now(timezone.utc) + timedelta(days=days_valid)
    return generator.generate_key(tier, holder_id, expiration)
