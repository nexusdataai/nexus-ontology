#!/bin/bash
# Startup script for MCP HTTP Gateway with streaming support

echo "Starting AI Job Engine MCP HTTP Gateway..."
echo "=========================================="

# Load environment variables from .env.local if it exists
if [ -f ".env.local" ]; then
    echo "Loading environment from .env.local..."
    set -a
    source .env.local
    set +a
fi

# Set AWS profile if not already set
export AWS_PROFILE=${AWS_PROFILE:-external-access}

# Set AWS region - IMPORTANT: must be set before any AWS SDK calls
export AWS_REGION=${AWS_REGION:-us-east-1}
export AWS_DEFAULT_REGION=${AWS_DEFAULT_REGION:-$AWS_REGION}

# Set environment (dev, stage, test, prod) - determines resource naming
export ENVIRONMENT=${ENVIRONMENT:-dev}

# Resource names follow: call-processing-{env}-{resource-name}
# These are auto-generated by config_provider.py if not explicitly set
# Uncomment to override:
# export DYNAMODB_TABLE=${DYNAMODB_TABLE:-call-processing-${ENVIRONMENT}-transformation-system}
# export LICENSE_TABLE=${LICENSE_TABLE:-call-processing-${ENVIRONMENT}-license}
# export WXCC_TASK_TABLE=${WXCC_TASK_TABLE:-call-processing-${ENVIRONMENT}-wxcc-task-tracking}
# export S3_RECORDINGS_BUCKET=${S3_RECORDINGS_BUCKET:-call-processing-${ENVIRONMENT}-call-data}
# export WXCC_SIMULATOR_BUCKET=${WXCC_SIMULATOR_BUCKET:-call-processing-${ENVIRONMENT}-wxcc-simulator}
# export S3_JOURNEY_LOGS_BUCKET=${S3_JOURNEY_LOGS_BUCKET:-call-processing-${ENVIRONMENT}-journey-logs}
# export S3_JOURNEY_REPORTS_BUCKET=${S3_JOURNEY_REPORTS_BUCKET:-call-processing-${ENVIRONMENT}-journey-reports}

# Set server configuration
export MIN_WORKERS=${MIN_WORKERS:-2}
export MAX_WORKERS=${MAX_WORKERS:-8}
export MCP_REQUEST_TIMEOUT=${MCP_REQUEST_TIMEOUT:-300.0}
export API_KEY=${API_KEY:-super-secret}
export LOG_LEVEL=${LOG_LEVEL:-INFO}

echo "Configuration:"
echo "  ENVIRONMENT: $ENVIRONMENT"
echo "  AWS_PROFILE: $AWS_PROFILE"
echo "  AWS_REGION: $AWS_REGION"
echo "  MIN_WORKERS: $MIN_WORKERS"
echo "  MAX_WORKERS: $MAX_WORKERS"
echo "  MCP_REQUEST_TIMEOUT: $MCP_REQUEST_TIMEOUT"
echo "  LOG_LEVEL: $LOG_LEVEL"
echo ""
echo "Resource Naming Convention: call-processing-${ENVIRONMENT}-{resource}"
echo ""

# Check if virtual environment exists
if [ -d ".venv" ]; then
    echo "Activating virtual environment..."
    source .venv/bin/activate
else
    echo "Warning: No virtual environment found at .venv"
    echo "Consider creating one with: uv venv"
fi

# Start the gateway
echo "Starting gateway on port 8000..."
python mcp_http_gateway.py --host 0.0.0.0 --port 8000

# Alternative for development with auto-reload:
# python mcp_http_gateway.py --host 0.0.0.0 --port 8000 --reload
