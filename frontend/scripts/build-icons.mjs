/**
 * Compiles the SVG icons in src/assets/icons/magnific into
 * src/components/ds/icons.generated.ts.
 *
 *   npm run icons
 *
 * Each SVG is cleaned so it is safe to inline and follows the text colour:
 *  - scripts, styles, event handlers, links, metadata and ids are removed
 *  - every fill / stroke colour becomes currentColor ("none" is kept)
 *  - width / height are dropped; the viewBox is kept
 *
 * To add an icon: put <name>.svg (same family as the rest) in the folder,
 * run the script, then use <Icon name="<name>" />.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src/assets/icons/magnific');
const outFile = join(root, 'src/components/ds/icons.generated.ts');

const ALLOWED = new Set(['path', 'g', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const KEEP_ATTRS = new Set([
  'd', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'y1', 'x2', 'y2', 'width', 'height', 'points',
  'transform', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin',
  'stroke-miterlimit', 'fill-rule', 'clip-rule', 'opacity', 'fill-opacity', 'stroke-opacity',
]);

function clean(svg) {
  const vb = svg.match(/viewBox\s*=\s*"([^"]+)"/i);
  let viewBox = vb ? vb[1].trim() : null;
  if (!viewBox) {
    const w = svg.match(/<svg[^>]*\swidth\s*=\s*"([\d.]+)/i);
    const h = svg.match(/<svg[^>]*\sheight\s*=\s*"([\d.]+)/i);
    viewBox = `0 0 ${w ? w[1] : 24} ${h ? h[1] : 24}`;
  }

  let inner = svg
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<!DOCTYPE[\s\S]*?>/gi, '')
    .replace(/<(script|style|defs|metadata|title|desc|foreignObject)[\s\S]*?<\/\1>/gi, '')
    .replace(/^[\s\S]*?<svg[^>]*>/i, '')
    .replace(/<\/svg>\s*$/i, '');

  // Rebuild every tag from an allow-list of elements and attributes.
  inner = inner.replace(/<(\/?)([a-zA-Z][\w:-]*)([^>]*?)(\/?)>/g, (_, close, tag, attrs, selfClose) => {
    const t = tag.toLowerCase();
    if (!ALLOWED.has(t)) return '';
    if (close) return `</${t}>`;
    const kept = [];
    for (const m of attrs.matchAll(/([a-zA-Z_:][\w:.-]*)\s*=\s*"([^"]*)"/g)) {
      const name = m[1].toLowerCase();
      let value = m[2];
      if (!KEEP_ATTRS.has(name)) continue;
      if ((name === 'fill' || name === 'stroke') && value.toLowerCase() !== 'none') value = 'currentColor';
      if (/url\(|javascript:|</i.test(value)) continue;
      kept.push(`${name}="${value}"`);
    }
    return `<${t}${kept.length ? ' ' + kept.join(' ') : ''}${selfClose ? '/' : ''}>`;
  });

  return { viewBox, body: inner.replace(/\s+/g, ' ').replace(/> </g, '><').trim() };
}

const files = readdirSync(srcDir).filter(f => f.endsWith('.svg')).sort();
const entries = files.map(f => {
  const name = f.replace(/\.svg$/, '');
  const { viewBox, body } = clean(readFileSync(join(srcDir, f), 'utf8'));
  return `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(body)} },`;
});

writeFileSync(outFile, [
  '/* AUTO-GENERATED by scripts/build-icons.mjs. Do not edit by hand. */',
  'export interface IconDef { viewBox: string; body: string }',
  'export const ICONS: Record<string, IconDef> = {',
  ...entries,
  '};',
  '',
].join('\n'));

console.log(`icons: ${files.length} compiled -> ${outFile}`);
